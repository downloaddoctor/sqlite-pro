import { createRequire } from 'node:module'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const ts = require('typescript')
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCES = ['src/types.ts', 'src/index.ts']

function docOf(node) {
  // Read JSDoc from the AST node (getLeadingCommentRanges is gone in TypeScript 6).
  if (!node.jsDoc || node.jsDoc.length === 0) return null
  const comment = node.jsDoc[0].comment
  if (!comment) return null
  const raw = Array.isArray(comment)
    ? comment.map((part) => (typeof part === 'string' ? part : part.text || '')).join('')
    : comment
  return raw.replace(/\s+/g, ' ').trim()
}

function memberLine(source, member) {
  const printer = ts.createPrinter({ removeComments: true })
  return printer.printNode(ts.EmitHint.Unspecified, member, source).replace(/;\s*$/, '')
}

function extract(sourceFile) {
  const kinds = []
  const counts = new Map()
  for (const stmt of sourceFile.statements) {
    if (ts.isFunctionDeclaration(stmt) && stmt.name) {
      counts.set(stmt.name.text, (counts.get(stmt.name.text) || 0) + 1)
    }
  }
  for (const stmt of sourceFile.statements) {
    const mods = stmt.modifiers || []
    if (!mods.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)) continue
    if (ts.isInterfaceDeclaration(stmt)) {
      kinds.push({
        type: 'interface',
        name: stmt.name.text,
        doc: docOf(stmt),
        members: stmt.members.map((member) => ({
          doc: docOf(member),
          line: memberLine(sourceFile, member),
        })),
      })
    } else if (ts.isTypeAliasDeclaration(stmt)) {
      kinds.push({
        type: 'type',
        name: stmt.name.text,
        doc: docOf(stmt),
        text: stmt.getText(sourceFile),
      })
    } else if (ts.isFunctionDeclaration(stmt) && stmt.name) {
      if ((counts.get(stmt.name.text) || 0) > 1 && stmt.body) continue
      const params = stmt.parameters.map((p) => p.getText(sourceFile)).join(', ')
      const typeParams = stmt.typeParameters
        ? '<' + stmt.typeParameters.map((t) => t.getText(sourceFile)).join(', ') + '>'
        : ''
      const ret = stmt.type ? ': ' + stmt.type.getText(sourceFile) : ''
      kinds.push({
        type: 'function',
        name: stmt.name.text,
        doc: docOf(stmt),
        text: 'export function ' + stmt.name.text + typeParams + '(' + params + ')' + ret,
      })
    } else if (ts.isExportDeclaration(stmt) && stmt.namedExports) {
      for (const element of stmt.namedExports.elements) {
        kinds.push({
          type: 'export',
          name: element.name.text,
          doc: null,
          text: 'export { ' + element.name.text + ' }',
        })
      }
    }
  }
  return kinds.sort((a, b) => a.name.localeCompare(b.name))
}

function render(kinds) {
  const parts = []
  for (const k of kinds) {
    parts.push('### `' + k.name + '`\n')
    if (k.doc) parts.push('> ' + k.doc + '\n')
    if (k.type === 'interface' && k.members.length) {
      parts.push('```ts')
      for (const member of k.members) {
        if (member.doc) parts.push('// ' + member.doc)
        parts.push(member.line)
      }
      parts.push('```')
    } else {
      parts.push('```ts\n' + k.text + '\n```')
    }
    parts.push('')
  }
  return parts.join('\n')
}

async function main() {
  const sections = []
  for (const file of SOURCES) {
    const sourceText = await readFile(path.join(ROOT, file), 'utf8')
    const source = ts.createSourceFile(
      file,
      sourceText,
      ts.ScriptTarget.Latest,
      true,
      ts.ScriptKind.TS,
    )
    sections.push('## `' + file + '`\n\n' + render(extract(source)))
  }
  const md =
    '# API Reference\n\nGenerated by `scripts/api-ref.mjs` from the TypeScript sources; do not edit by hand.\n\n' +
    sections.join('\n---\n\n') +
    '\n'
  await mkdir(path.join(ROOT, 'docs'), { recursive: true })
  await writeFile(path.join(ROOT, 'docs', 'API.md'), md)
  console.log('docs/API.md written (' + md.split('\n').length + ' lines)')
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
